#!/usr/bin/env python3
"""
DBTT(C) Linear Modeling Pipeline (composition-focused)
------------------------------------------------------
Author: (generated by GPT-5 Pro)

What it does
------------
- Loads a CSV and models DBTT(C) from *composition-only* features, with optional
  inclusion of mechanical properties (hardness / tensile strength) if present enough.
- Handles per-row composition basis via an 'at/wt' column (auto/convert to wt% or at%).
- Balances composition to 100 by adjusting V to absorb any deficit/excess.
- Creates a synthetic AlloyID from composition to enable grouped CV.
- Detects outliers with LOF and runs the analysis *with and without* outliers.
- Produces a histogram of the percent non-null values across candidate features to
  help pick a missingness threshold.
- Saves metrics, coefficients, permutation importances, plots, and a cleaned snapshot.

Usage
-----
python dbtt_linear_regression.py --csv <path> \
    --target "DBTT(C)" \
    --out-dir dbtt_outputs \
    --basis-policy auto \
    --include-mech True \
    --mech-min-frac 0.60 \
    --feature-threshold 0.00 \
    --grouped-cv True \
    --n-splits 5 \
    --lof-contamination 0.10 \
    --random-state 42

Notes
-----
- We only use composition columns (element symbols like V, Cr, Ti, ...). All other
  non-composition columns are excluded *except* hardness / tensile strength, which
  can be optionally included if present enough.
- DBTT definition: assumed Charpy V-notch derived and comparable across rows.
- Grain size intentionally ignored per user guidance.
"""

